//! Build the three demo frames, `frames.h`, and preview PNGs.

use std::fs;
use std::path::Path;

use crate::box_resize::{box_resize, threshold};
use crate::font::{FontKind, Fonts};
use crate::png_rgb;
use crate::svg::{svg_rgba, to_bits};

pub const W: u32 = 128;
pub const H: u32 = 64;
const SCALE: u32 = 4;

pub struct Frame {
    pub name: &'static str,
    pub pixels: Vec<u8>,
}

pub struct Draw {
    pub pixels: Vec<u8>,
    /// Matches ImageDraw.fontmode: starts as `"L"` (`false`) on a new image.
    pub mono_measure: bool,
}

impl Default for Draw {
    fn default() -> Self {
        Self {
            pixels: vec![0u8; (W * H) as usize],
            mono_measure: false,
        }
    }
}

impl Draw {
    pub fn new() -> Self {
        Self::default()
    }

    fn text_length(
        &self,
        fonts: &Fonts,
        s: &str,
        kind: FontKind,
        size: i32,
    ) -> Result<f64, String> {
        fonts.text_length(s, kind, size, self.mono_measure)
    }

    #[allow(clippy::too_many_arguments)]
    pub fn center_text(
        &mut self,
        fonts: &Fonts,
        y: f64,
        s: &str,
        kind: FontKind,
        size: i32,
        x0: f64,
        x1: f64,
    ) -> Result<(), String> {
        let width = self.text_length(fonts, s, kind, size)?;
        let x = x0 + (x1 - x0 - width).div_euclid(2.0);
        // After the first measure, gen_frames.py sets fontmode to "1".
        self.mono_measure = true;
        fonts.draw_text(&mut self.pixels, W as i32, H as i32, x, y, s, kind, size)
    }

    pub fn text(
        &mut self,
        fonts: &Fonts,
        x: f64,
        y: f64,
        s: &str,
        kind: FontKind,
        size: i32,
    ) -> Result<(), String> {
        self.mono_measure = true;
        fonts.draw_text(&mut self.pixels, W as i32, H as i32, x, y, s, kind, size)
    }

    pub fn hline(&mut self, y: u32) {
        if y >= H {
            return;
        }
        for x in 0..W {
            self.pixels[(y * W + x) as usize] = 255;
        }
    }

    pub fn paste(&mut self, mask: &[u8], mw: u32, mh: u32, x0: i32, y0: i32) {
        for y in 0..mh {
            for x in 0..mw {
                let v = mask[(y * mw + x) as usize];
                if v == 0 {
                    continue;
                }
                let dx = x0 + x as i32;
                let dy = y0 + y as i32;
                if dx >= 0 && dy >= 0 && dx < W as i32 && dy < H as i32 {
                    self.pixels[(dy as u32 * W + dx as u32) as usize] = 255;
                }
            }
        }
    }
}

fn lum_gt90(r: u8, g: u8, b: u8, a: u8) -> bool {
    a > 128 && (0.299 * f64::from(r) + 0.587 * f64::from(g) + 0.114 * f64::from(b)) > 90.0
}

fn lum_lt225(r: u8, g: u8, b: u8, a: u8) -> bool {
    a > 128 && (0.299 * f64::from(r) + 0.587 * f64::from(g) + 0.114 * f64::from(b)) < 225.0
}

fn getbbox(mask: &[u8], w: u32, h: u32) -> Option<(u32, u32, u32, u32)> {
    let mut min_x = w;
    let mut min_y = h;
    let mut max_x = 0u32;
    let mut max_y = 0u32;
    let mut any = false;
    for y in 0..h {
        for x in 0..w {
            if mask[(y * w + x) as usize] != 0 {
                any = true;
                if x < min_x {
                    min_x = x;
                }
                if y < min_y {
                    min_y = y;
                }
                if x + 1 > max_x {
                    max_x = x + 1;
                }
                if y + 1 > max_y {
                    max_y = y + 1;
                }
            }
        }
    }
    if any {
        Some((min_x, min_y, max_x, max_y))
    } else {
        None
    }
}

fn crop(mask: &[u8], w: u32, box_: (u32, u32, u32, u32)) -> (Vec<u8>, u32, u32) {
    let (x0, y0, x1, y1) = box_;
    let cw = x1 - x0;
    let ch = y1 - y0;
    let mut out = vec![0u8; (cw * ch) as usize];
    for y in 0..ch {
        for x in 0..cw {
            out[(y * cw + x) as usize] = mask[((y0 + y) * w + (x0 + x)) as usize];
        }
    }
    (out, cw, ch)
}

fn pack_ssd1306(pixels: &[u8]) -> [u8; 1024] {
    let mut buf = [0u8; 1024];
    let mut i = 0;
    for page in 0..8 {
        for x in 0..W {
            let mut v = 0u8;
            for bit in 0..8 {
                let y = page * 8 + bit;
                if pixels[(y * W + x) as usize] != 0 {
                    v |= 1 << bit;
                }
            }
            buf[i] = v;
            i += 1;
        }
    }
    buf
}

pub fn frames_header(frames: &[Frame]) -> String {
    let mut lines = vec![
        "/* Generated by tools/gen-frames. 128x64, SSD1306 page order (8 pages x 128 cols, LSB = top row), 1 = lit. */"
            .to_string(),
        "#pragma once".into(),
        "#include <stdint.h>".into(),
        format!("#define DEMO_FRAME_COUNT {}", frames.len()),
    ];
    for frame in frames {
        let buf = pack_ssd1306(&frame.pixels);
        lines.push(format!(
            "static const uint8_t frame_{}[1024] = {{",
            frame.name
        ));
        for chunk in buf.chunks(16) {
            let body = chunk
                .iter()
                .map(|b| format!("0x{b:02x}"))
                .collect::<Vec<_>>()
                .join(", ");
            lines.push(format!("  {body},"));
        }
        lines.push("};".into());
    }
    let names = frames
        .iter()
        .map(|f| format!("frame_{}", f.name))
        .collect::<Vec<_>>()
        .join(", ");
    lines.push(format!(
        "static const uint8_t *const demo_frames[DEMO_FRAME_COUNT] = {{{names}}};"
    ));
    lines.join("\n") + "\n"
}

fn preview_rgb(pixels: &[u8]) -> (u32, u32, Vec<u8>) {
    let pw = W * SCALE;
    let ph = H * SCALE;
    let mut data = vec![0u8; (pw * ph * 3) as usize];
    for y in 0..H {
        for x in 0..W {
            if pixels[(y * W + x) as usize] == 0 {
                continue;
            }
            for dy in 0..SCALE {
                for dx in 0..SCALE {
                    let i = (((y * SCALE + dy) * pw + (x * SCALE + dx)) * 3) as usize;
                    data[i] = 235;
                    data[i + 1] = 245;
                    data[i + 2] = 255;
                }
            }
        }
    }
    (pw, ph, data)
}

fn preview_strip(frames: &[Frame]) -> (u32, u32, Vec<u8>) {
    let pad = 16u32;
    let fw = W * SCALE;
    let fh = H * SCALE;
    let width = fw + 2 * pad;
    let height = frames.len() as u32 * (fh + pad) + pad;
    let mut data = vec![0u8; (width * height * 3) as usize];
    for px in data.chunks_exact_mut(3) {
        px[0] = 40;
        px[1] = 40;
        px[2] = 40;
    }
    for (i, frame) in frames.iter().enumerate() {
        let (_, _, p) = preview_rgb(&frame.pixels);
        let x0 = pad;
        let y0 = pad + i as u32 * (fh + pad);
        for y in 0..fh {
            for x in 0..fw {
                let src = ((y * fw + x) * 3) as usize;
                let dst = (((y0 + y) * width + (x0 + x)) * 3) as usize;
                data[dst] = p[src];
                data[dst + 1] = p[src + 1];
                data[dst + 2] = p[src + 2];
            }
        }
    }
    (width, height, data)
}

pub fn build_frames(assets: &Path, fonts: &Fonts) -> Result<Vec<Frame>, String> {
    let mut frames = Vec::new();

    // 1. moq.dev
    let icon = svg_rgba(&assets.join("moqdev-layout_favicon.svg"), 512, Some(512))?;
    let (mark, mw, mh) = to_bits(&icon, lum_gt90);
    let small = threshold(&box_resize(&mark, mw as usize, mh as usize, 60, 60), 110);
    let mut f1 = Draw::new();
    f1.paste(&small, 60, 60, 2, 2);
    f1.center_text(fonts, 8.0, "moq.dev", FontKind::SansBold, 13, 64.0, 128.0)?;
    f1.center_text(fonts, 30.0, "Media over", FontKind::Sans, 10, 64.0, 128.0)?;
    f1.center_text(fonts, 42.0, "QUIC", FontKind::SansBold, 10, 64.0, 128.0)?;
    frames.push(Frame {
        name: "moq",
        pixels: f1.pixels,
    });

    // 2. rind wordmark
    let wm = svg_rgba(&assets.join("wordmark-light.svg"), 1000, None)?;
    let (mask, ww, wh) = to_bits(&wm, lum_lt225);
    let bbox = getbbox(&mask, ww, wh).ok_or_else(|| "wordmark mask is empty".to_string())?;
    let (cropped, cw, ch) = crop(&mask, ww, bbox);
    let dh = 48u32;
    let dw = ((f64::from(cw) * f64::from(dh)) / f64::from(ch)).round() as u32;
    let wsmall = threshold(
        &box_resize(&cropped, cw as usize, ch as usize, dw as usize, dh as usize),
        100,
    );
    let mut f2 = Draw::new();
    let x = (W as i32 - dw as i32) / 2;
    f2.paste(&wsmall, dw, dh, x, 1);
    f2.center_text(
        fonts,
        52.0,
        "pure-Rust crypto",
        FontKind::Sans,
        9,
        0.0,
        128.0,
    )?;
    frames.push(Frame {
        name: "rind",
        pixels: f2.pixels,
    });

    // 3. Benchmark headline
    let mut f3 = Draw::new();
    f3.center_text(
        fonts,
        0.0,
        "TLS 1.3 handshake",
        FontKind::SansBold,
        9,
        0.0,
        128.0,
    )?;
    f3.center_text(fonts, 10.0, "X25519, full", FontKind::Sans, 9, 0.0, 128.0)?;
    f3.hline(21);
    let rows: [(&str, &str, &str); 4] = [
        ("", "rind", "aws-lc"),
        ("Xeon", "228\u{00b5}s", "299\u{00b5}s"),
        ("M1 Pro", "284\u{00b5}s", "425\u{00b5}s"),
        ("A76", "1.57ms", "1.33ms"),
    ];
    for (i, (a, b, c)) in rows.iter().enumerate() {
        let y = 23.0 + (i as f64) * 10.0;
        let kind = if i == 0 {
            FontKind::SansBold
        } else {
            FontKind::Sans
        };
        f3.text(fonts, 0.0, y, a, kind, 9)?;
        f3.text(fonts, 48.0, y, b, kind, 9)?;
        f3.text(fonts, 90.0, y, c, kind, 9)?;
    }
    frames.push(Frame {
        name: "bench",
        pixels: f3.pixels,
    });

    Ok(frames)
}

/// Write `oled_demo/frames.h` and the preview PNGs under `out` (the oled-demo root).
pub fn generate(out: &Path, font_dir: &Path) -> Result<Vec<&'static str>, String> {
    let assets = out.join("assets");
    if !assets.is_dir() {
        return Err(format!("{}: missing assets directory", assets.display()));
    }
    let fonts = Fonts::new(font_dir)?;
    let frames = build_frames(&assets, &fonts)?;
    let names: Vec<&'static str> = frames.iter().map(|f| f.name).collect();

    let oled = out.join("oled_demo");
    fs::create_dir_all(&oled).map_err(|e| format!("{}: {e}", oled.display()))?;
    fs::write(oled.join("frames.h"), frames_header(&frames))
        .map_err(|e| format!("{}: {e}", oled.join("frames.h").display()))?;

    for (i, frame) in frames.iter().enumerate() {
        let (pw, ph, data) = preview_rgb(&frame.pixels);
        let path = out.join(format!("preview-{}-{}.png", i + 1, frame.name));
        png_rgb::write_rgb(&path, pw, ph, &data)?;
    }
    let (sw, sh, strip) = preview_strip(&frames);
    png_rgb::write_rgb(&out.join("preview.png"), sw, sh, &strip)?;
    Ok(names)
}
